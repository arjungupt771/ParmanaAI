
import { useState, type FormEvent } from 'react'
import {
  Activity,
  ArrowUpRight,
  BookOpen,
  FileCheck2,
  FlaskConical,
  LoaderCircle,
  Sparkles,
  AlertCircle,
} from 'lucide-react'

import PageHeader from '../components/ui/PageHeader'
import MetricCard from '../components/ui/MetricCard'
import ClaimResultCard from '../components/claims/ClaimResultCard'
import { useAskQuestion } from '../hooks/useAskQuestion'
import { getApiErrorMessage } from '../services/api'
import { useAnalysisContext } from '../context/AnalysisContext'

function Workspace() {
  const [question, setQuestion] = useState('')
  const [externalContext, setExternalContext] = useState('')
  const analysis = useAskQuestion()
  const { setAnalysis, clearAnalysis } = useAnalysisContext()

  const response = analysis.data

  const handleSubmit = (event: FormEvent<HTMLFormElement>) => {
    event.preventDefault()

    const cleanedQuestion = question.trim()

    if (!cleanedQuestion || analysis.isPending) {
      return
    }

    analysis.mutate(
      {
        query: cleanedQuestion,
        ...(externalContext.trim()
          ? { external_context: externalContext.trim() }
          : {}),
      },
      {
        onSuccess: (data) => {
          setAnalysis(cleanedQuestion, data)
        },
      },
    )
  }

  const handleReset = () => {
    analysis.reset()
    clearAnalysis()
    setQuestion('')
    setExternalContext('')
  }

  return (
    <>
      <PageHeader
        eyebrow="YOUR RESEARCH ENVIRONMENT"
        title="Evidence Workspace"
        description="Analyze claims, inspect supporting evidence, and evaluate numerical consistency."
      />

      <section className="workspace-hero">
        <div className="hero-glow" />

        <div className="hero-content">
          <div className="hero-label">
            <Sparkles size={14} />
            EVIDENCE-GROUNDED INTELLIGENCE
          </div>

          <h2>
            Ask a question.
            <br />
            <span>Examine the evidence.</span>
          </h2>

          <p>
            Explore medical claims against retrieved research
            evidence, with claim-level verification and numerical
            consistency analysis.
          </p>

          <form
            className="hero-input-area"
            onSubmit={handleSubmit}
          >
            <textarea
              value={question}
              onChange={(event) => setQuestion(event.target.value)}
              placeholder="Enter a research question or medical claim..."
              rows={3}
              required
              disabled={analysis.isPending}
              aria-label="Research question"
            />

            <details className="external-context-details">
              <summary>Provide external context (optional)</summary>

              <textarea
                className="external-context-input"
                value={externalContext}
                onChange={(event) =>
                  setExternalContext(event.target.value)
                }
                placeholder="Paste additional context to analyze. This material is unverified..."
                rows={4}
                disabled={analysis.isPending}
              />
            </details>

            <div className="hero-input-footer">
              <span>
                {analysis.isPending
                  ? 'Analyzing your question...'
                  : 'Results are generated by the ParmanaAI backend.'}
              </span>

              <button
                type="submit"
                className="primary-button"
                disabled={!question.trim() || analysis.isPending}
              >
                {analysis.isPending ? (
                  <>
                    <LoaderCircle className="spin-icon" size={15} />
                    Analyzing
                  </>
                ) : (
                  <>
                    Analyze
                    <ArrowUpRight size={16} />
                  </>
                )}
              </button>
            </div>
          </form>
        </div>

        <div className="hero-decoration">
          <div className="decoration-ring ring-one" />
          <div className="decoration-ring ring-two" />
          <div className="decoration-core">
            <Activity size={36} />
          </div>
          <div className="decoration-node node-one" />
          <div className="decoration-node node-two" />
          <div className="decoration-node node-three" />
        </div>
      </section>

      {analysis.isError && (
        <div className="api-error-panel" role="alert">
          <AlertCircle size={19} />

          <div>
            <strong>Analysis could not be completed</strong>
            <p>
              {getApiErrorMessage(analysis.error)}
            </p>
            <span>
              Check that the FastAPI backend is running and the API URL
              is configured correctly.
            </span>
          </div>

          <button
            className="text-action"
            onClick={() => {
              const cleanedQuestion = question.trim()

              analysis.mutate(
                {
                  query: cleanedQuestion,
                  ...(externalContext.trim()
                    ? { external_context: externalContext.trim() }
                    : {}),
                },
                {
                  onSuccess: (data) => {
                    setAnalysis(cleanedQuestion, data)
                  },
                },
              )
            }}
            disabled={!question.trim() || analysis.isPending}
          >
            Retry
          </button>
        </div>
      )}

      {response && (
        <section className="analysis-results">
          <div className="analysis-results-header">
            <div>
              <div className="page-eyebrow">ANALYSIS COMPLETE</div>
              <h2>Research results</h2>
              <p>
                The following output was returned by the ParmanaAI backend.
              </p>
            </div>

            <button
              className="secondary-button"
              onClick={handleReset}
            >
              New analysis
            </button>
          </div>

          <div className="metrics-grid">
            <MetricCard
              label="Claims extracted"
              value={String(response.claims.length)}
              description="Claims returned by the verifier"
              icon={FileCheck2}
            />

            <MetricCard
              label="Hallucination score"
              value={response.hallucination_score.toFixed(3)}
              description="Project-level heuristic, not calibrated probability"
              icon={Activity}
            />

            <MetricCard
              label="Relevance score"
              value={response.relevance_score.toFixed(3)}
              description="Backend relevance metric"
              icon={BookOpen}
            />

            <MetricCard
              label="Numerical analysis"
              value={
                response.claims.filter(
                  (claim) =>
                    claim.numerical_assessment !== undefined,
                ).length.toString()
              }
              description="Claims containing numerical assessment data"
              icon={FlaskConical}
            />
          </div>

          <section className="section-block">
            <div className="section-heading">
              <div>
                <h2>Generated answer</h2>
                <p>Response from the evidence-grounded pipeline</p>
              </div>
            </div>

            <div className="answer-panel">
              {response.answer}
            </div>
          </section>

          <section className="section-block">
            <div className="section-heading">
              <div>
                <h2>Claim-level verification</h2>
                <p>
                  {response.claims.length} claim(s) returned by the backend
                </p>
              </div>
            </div>

            {response.claims.length > 0 ? (
              <div className="claim-results-list">
                {response.claims.map((claim, index) => (
                  <ClaimResultCard
                    key={
                      typeof claim.claim_id === 'string'
                        ? claim.claim_id
                        : index
                    }
                    claim={claim}
                    index={index}
                  />
                ))}
              </div>
            ) : (
              <div className="content-panel">
                <div className="empty-state">
                  <FileCheck2 size={25} />
                  <h3>No claims were returned</h3>
                  <p>
                    The backend completed the request but did not
                    return extracted claims.
                  </p>
                </div>
              </div>
            )}
          </section>
        </section>
      )}
    </>
  )
}

export default Workspace
